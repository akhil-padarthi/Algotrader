"""The same journal and user-account code on PostgreSQL (what Supabase runs).

These run only when POSTGRES_TEST_URL points at a PostgreSQL server you can create schemas on, e.g.
  POSTGRES_TEST_URL=postgresql://postgres@127.0.0.1:5432/postgres?sslmode=disable
They drop and recreate the ``algotrader`` schema, so never point them at a database with real data.
The translation helpers are tested always.
"""
