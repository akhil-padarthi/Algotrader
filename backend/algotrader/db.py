"""Where the journal and the user accounts are stored: SQLite files (default) or PostgreSQL.

Set DATABASE_URL to a PostgreSQL connection string (for example Supabase's) to keep the data in that
database instead of the files in backend/data. Everything else in the app is the same either way:
queries are written once with ``?`` placeholders and translated for PostgreSQL here.

On PostgreSQL the tables live in their own schema, ``algotrader``, which Supabase's automatic REST API
does not expose, and row-level security is switched on for each of them as a second lock. The app
connects as the database owner, so it is not affected by either.
"""
from __future__ import annotations

import re
import sqlite3
import threading
import time
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import parse_qs, quote, urlsplit

PG_SCHEMA = "algotrader"
POOL_SIZE = 4                 # open connections kept per process
CHECK_AFTER = 60.0            # seconds idle before a pooled connection is tested again


class DatabaseError(RuntimeError):
    """The database can't be reached or isn't set up right; the message says how to fix it."""


def is_postgres(target) -> bool:
    return str(target).strip().startswith(("postgres://", "postgresql://"))


_ENCODED = re.compile(r"(?:[A-Za-z0-9\-._~]|%[0-9A-Fa-f]{2})*")


def normalize_url(url: str) -> str:
    """Accept a connection string with the password pasted as-is.

    Characters such as / & @ # ? or spaces in a password break a URL, so they are percent-encoded
    here (a password that is already encoded is left alone). The host is everything after the last @.
    """
    url = str(url).strip()
    if not is_postgres(url) or "@" not in url.split("://", 1)[1]:
        return url
    scheme, rest = url.split("://", 1)
    userinfo, hostpart = rest.rsplit("@", 1)
    user, sep, password = userinfo.partition(":")
    if _ENCODED.fullmatch(user) and _ENCODED.fullmatch(password):
        return url
    return f"{scheme}://{quote(user, safe='')}{sep}{quote(password, safe='')}@{hostpart}"


def _parts(url: str):
    u = urlsplit(url)
    try:
        u.port
    except ValueError as exc:
        raise DatabaseError("DATABASE_URL isn't a valid connection string. Copy it again from Supabase "
                            "(Connect > Session pooler) and put your database password in place of [YOUR-PASSWORD].") from exc
    return u


def describe(target) -> str:
    """Where the data is, without the password."""
    if not is_postgres(target):
        return f"SQLite file {target}"
    try:
        u = _parts(normalize_url(target))
    except DatabaseError:
        return "PostgreSQL database (connection string can't be read)"
    host = u.hostname or "?"
    kind = "Supabase" if host.endswith(("supabase.com", "supabase.co")) else "PostgreSQL"
    return f"{kind} database {u.username or ''}@{host}:{u.port or 5432}{u.path or ''}"


def _driver():
    try:
        import psycopg
    except ImportError as exc:  # pragma: no cover - depends on the install
        raise DatabaseError("DATABASE_URL points to a PostgreSQL database, which needs the 'psycopg' package. "
                            "In the backend folder run: pip install -r requirements.txt") from exc
    return psycopg


def to_postgres_sql(sql: str) -> str:
    """``?`` placeholders -> ``%s`` (and a literal ``%`` -> ``%%``), outside quoted strings."""
    out, quoted = [], False
    for ch in sql:
        if ch == "'":
            quoted = not quoted
            out.append(ch)
        elif ch == "%":
            out.append("%%")
        elif ch == "?" and not quoted:
            out.append("%s")
        else:
            out.append(ch)
    return "".join(out)


def to_postgres_schema(script: str) -> list[str]:
    """Translate a SQLite CREATE script into PostgreSQL statements."""
    script = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script)
    script = re.sub(r"\bREAL\b", "DOUBLE PRECISION", script)
    script = script.replace(" COLLATE NOCASE", "")
    return [s.strip() for s in script.split(";") if s.strip()]


class _Row(dict):
    """A result row usable both as row["column"] and row[0], like sqlite3.Row."""

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description or []]
    return lambda values: _Row(names, values)


class Connection:
    """One transaction's connection, with the same small API on both databases."""

    def __init__(self, raw, postgres: bool):
        self.raw = raw
        self.postgres = postgres

    def execute(self, sql: str, params=()):
        if not self.postgres:
            return self.raw.execute(sql, params)
        cur = self.raw.cursor(row_factory=_row_factory)
        if params:
            cur.execute(to_postgres_sql(sql), tuple(params))
        else:
            cur.execute(sql)
        return cur

    def executemany(self, sql: str, rows) -> None:
        rows = [tuple(r) for r in rows]
        if not rows:
            return
        if self.postgres:
            self.raw.cursor().executemany(to_postgres_sql(sql), rows)
        else:
            self.raw.executemany(sql, rows)

    def insert(self, sql: str, params=()) -> int:
        """Run an INSERT and return the new row's id."""
        if self.postgres:
            return int(self.execute(sql + " RETURNING id", params).fetchone()[0])
        return int(self.raw.execute(sql, params).lastrowid)


class _Pool:
    """A few open PostgreSQL connections, reused (opening one over the internet takes a moment)."""

    def __init__(self, url: str):
        self.url = url
        self.idle: list[tuple[object, float]] = []
        self.lock = threading.Lock()

    def _open(self):
        psycopg = _driver()
        extra = {}
        u = urlsplit(self.url)
        if "sslmode" not in parse_qs(u.query) and u.hostname not in ("localhost", "127.0.0.1", "::1"):
            extra["sslmode"] = "require"      # never fall back to an unencrypted connection
        try:
            conn = psycopg.connect(self.url, connect_timeout=15, prepare_threshold=None,
                                   application_name="algotrader", **extra)
        except psycopg.OperationalError as exc:
            raise DatabaseError(explain_connect_error(exc)) from exc
        conn.execute(f"SET search_path TO {PG_SCHEMA}, public")
        conn.commit()
        return conn

    def get(self):
        while True:
            with self.lock:
                item = self.idle.pop() if self.idle else None
            if item is None:
                return self._open()
            conn, last = item
            if conn.closed or conn.broken:
                continue
            if time.monotonic() - last > CHECK_AFTER:
                try:
                    conn.execute("SELECT 1")
                    conn.rollback()
                except Exception:
                    conn.close()
                    continue
            return conn

    def put(self, conn) -> None:
        with self.lock:
            if len(self.idle) < POOL_SIZE and not conn.closed:
                self.idle.append((conn, time.monotonic()))
                return
        conn.close()


_pools: dict[str, _Pool] = {}
_pools_lock = threading.Lock()


def _pool_for(url: str) -> _Pool:
    with _pools_lock:
        if url not in _pools:
            _pools[url] = _Pool(url)
        return _pools[url]


def explain_connect_error(exc) -> str:
    text = str(exc).strip().splitlines()[0] if str(exc).strip() else type(exc).__name__
    low = text.lower()
    if "password authentication failed" in low:
        hint = ("the password in DATABASE_URL is wrong. Use your database password (Supabase: Project Settings > "
                "Database), not your Supabase login password")
    elif "could not translate host name" in low or "name or service not known" in low or "nodename" in low:
        hint = "the host name in DATABASE_URL can't be found. Copy the connection string again"
    elif "network is unreachable" in low or "no route to host" in low:
        hint = ("this computer can't reach that address. On Supabase use the Session pooler connection string "
                "(it works on IPv4 networks)")
    elif "timeout" in low or "timed out" in low:
        hint = "the database didn't answer in time. Check your internet connection and the connection string"
    elif "tenant or user not found" in low:
        hint = "the user name is wrong. Supabase pooler user names look like postgres.yourprojectref"
    else:
        hint = "check the connection string in DATABASE_URL"
    return f"Can't connect to the database ({text}): {hint}."


class Database:
    """A SQLite file or a PostgreSQL database, chosen by the target (a path or a postgresql:// URL)."""

    def __init__(self, target):
        self.postgres = is_postgres(target)
        self.target = normalize_url(target) if self.postgres else str(target)
        if self.postgres:
            if _parts(self.target).port == 6543:
                raise DatabaseError("DATABASE_URL uses Supabase's transaction pooler (port 6543), which doesn't "
                                    "keep the settings this app needs. Use the Session pooler (port 5432) or the "
                                    "direct connection string instead.")
            self.integrity_errors = (_driver().IntegrityError,)
            self._pool = _pool_for(self.target)
        else:
            self.path = Path(target)
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.integrity_errors = (sqlite3.IntegrityError,)

    def describe(self) -> str:
        return describe(self.target)

    @contextmanager
    def connect(self):
        if not self.postgres:
            raw = sqlite3.connect(self.path, timeout=30)
            raw.row_factory = sqlite3.Row
            raw.execute("PRAGMA foreign_keys=ON")
            try:
                yield Connection(raw, False)
                raw.commit()
            finally:
                raw.close()
            return
        raw = self._pool.get()
        try:
            yield Connection(raw, True)
            raw.commit()
        except BaseException:
            try:
                raw.rollback()
            except Exception:
                raw.close()
            if not raw.closed:
                self._pool.put(raw)
            raise
        self._pool.put(raw)

    def create_tables(self, script: str, tables: list[str]) -> None:
        """Create the tables if they don't exist yet (a SQLite script, translated for PostgreSQL)."""
        if not self.postgres:
            with self.connect() as c:
                c.raw.execute("PRAGMA journal_mode=WAL")
                c.raw.executescript(script)
            return
        with self.connect() as c:
            c.execute(f"CREATE SCHEMA IF NOT EXISTS {PG_SCHEMA}")
            c.execute(f"SET search_path TO {PG_SCHEMA}, public")
            for statement in to_postgres_schema(script):
                c.execute(statement)
            for table in tables:
                c.execute(f"ALTER TABLE {PG_SCHEMA}.{table} ENABLE ROW LEVEL SECURITY")
            # Supabase's API roles get nothing here (they don't exist on a plain PostgreSQL server)
            c.execute(f"""
                DO $$
                DECLARE r text;
                BEGIN
                  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
                    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA {PG_SCHEMA} FROM %I', r);
                      EXECUTE format('REVOKE ALL ON SCHEMA {PG_SCHEMA} FROM %I', r);
                    END IF;
                  END LOOP;
                END $$""")

    def count(self, table: str) -> int:
        with self.connect() as c:
            return int(c.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0])

    def reset_ids(self, table: str) -> None:
        """After copying rows with their ids, let new rows continue after the highest id (PostgreSQL)."""
        if self.postgres:
            with self.connect() as c:
                c.execute(f"SELECT setval(pg_get_serial_sequence('{PG_SCHEMA}.{table}', 'id'), "
                          f"COALESCE((SELECT MAX(id) FROM {PG_SCHEMA}.{table}), 0) + 1, false)")
