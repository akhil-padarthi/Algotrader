@unittest.skipUnless(PG_URL, "set POSTGRES_TEST_URL to run against PostgreSQL")
class PgDatabaseTests(TempDirTest):
    def setUp(self):
        super().setUp()
        reset_schema()

    def test_journal_round_trip(self):
        j = Journal(PG_URL)
        run = j.start_run(dry_run=False)
        j.add_signals(run, "2026-10-16", [
            {"symbol": "AAPL", "proba": np.float64(0.62), "price": np.float32(253.1), "action": "BUY", "reason": "x",
             "held": np.int64(0)},
            {"symbol": "XOM", "proba": 0.41, "price": 111.0, "action": "SELL", "reason": "y", "held": 1}])
        j.add_order(run, symbol="AAPL", side="buy", qty=np.int64(3), reason="entry", price=np.float64(253.1),
                    client_order_id="algo-20261016-AAPL-buy", alpaca_order_id="o-1", status="accepted")
        j.add_order(None, symbol="MSFT", side="buy", qty=1, reason="manual", alpaca_order_id="o-2", status="new")
        j.finish_run(run, "ok", "done", as_of="2026-10-16", equity=100000.5, n_orders=1)
        latest = j.latest_signals()
        self.assertEqual(latest["run_id"], run)
        self.assertEqual([s["symbol"] for s in latest["signals"]], ["AAPL", "XOM"])
        self.assertAlmostEqual(latest["signals"][0]["proba"], 0.62)
        self.assertEqual(j.recent_runs(1)[0]["status"], "ok")
        self.assertEqual(j.bot_order_ids(), {"o-1"})
        self.assertEqual(j.manual_order_ids(), {"o-2"})
        self.assertEqual(j.last_buy("AAPL")["client_order_id"], "algo-20261016-AAPL-buy")   # LIKE 'algo-%'
        self.assertEqual(j.start_run(True), run + 1)

    def test_tables_are_private(self):
        """Own schema (not exposed by Supabase's REST API), row-level security on, no access for API roles."""
        db = Database(PG_URL)
        with db.connect() as c:
            for role in ("anon", "authenticated"):            # Supabase's API roles, simulated
                if not c.execute("SELECT 1 FROM pg_roles WHERE rolname=?", (role,)).fetchone():
                    c.execute(f"CREATE ROLE {role} NOLOGIN")
        UserStore(PG_URL, SecretBox("m"))
        Journal(PG_URL)
        with db.connect() as c:
            rows = c.execute("SELECT c.relname, c.relrowsecurity FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                             "WHERE n.nspname = ? AND c.relkind = 'r' ORDER BY 1", (PG_SCHEMA,)).fetchall()
            self.assertEqual([r[0] for r in rows],
                             ["login_attempts", "orders", "runs", "sessions", "signals", "trades", "users"])
            self.assertTrue(all(r[1] for r in rows))
            self.assertEqual(c.execute("SELECT COUNT(*) FROM pg_tables WHERE schemaname='public' AND tablename='users'")
                             .fetchone()[0], 0)
            for role in ("anon", "authenticated"):
                self.assertFalse(c.execute("SELECT has_table_privilege(?, 'algotrader.users', 'SELECT')", (role,))
                                 .fetchone()[0])
                self.assertFalse(c.execute("SELECT has_schema_privilege(?, 'algotrader', 'USAGE')", (role,)).fetchone()[0])

    def test_reuses_connections(self):
        db = Database(PG_URL)
        with db.connect() as c:
            first = c.execute("SELECT pg_backend_pid()").fetchone()[0]
        with db.connect() as c:
            again = c.execute("SELECT pg_backend_pid()").fetchone()[0]
        self.assertEqual(first, again)
        with self.assertRaises(Exception):                     # a failed transaction is rolled back...
            with db.connect() as c:
                c.execute("SELECT * FROM no_such_table")
        with db.connect() as c:                                # ...and the connection still works
            self.assertEqual(c.execute("SELECT 1").fetchone()[0], 1)

    def test_copy_local_data_into_postgres(self):
        from algotrader.cli import main
        local = UserStore(self.tmp / "users.db", SecretBox("copy material"))
        ana = local.create_user("ana@example.com", "Ana", test_accounts.PW)
        local.link_alpaca(ana["id"], "PKCOPYKEY1234567", "copysecretcopysecret", "https://paper", "PA99998888")
        local.record_trade(ana["id"], symbol="AAPL", side="buy", amount=50.0)
        jl = Journal(self.tmp / "algotrader.db")
        run = jl.start_run(False)
        jl.add_signals(run, "2026-10-16", [{"symbol": "AAPL", "proba": 0.6, "price": 1.0, "action": "BUY",
                                            "reason": "", "held": 0}])
        env = {"DATA_DIR": str(self.tmp), "SECRET_KEY": "copy material", "DATABASE_URL": PG_URL}
        out = io.StringIO()
        from unittest import mock
        with mock.patch.dict(os.environ, env, clear=True), contextlib.redirect_stdout(out):
            main(["--env-file", str(self.tmp / "none.env"), "db", "copy-from-sqlite"])
        self.assertIn("users: 1", out.getvalue())
        remote = UserStore(PG_URL, SecretBox("copy material"))
        self.assertEqual(remote.authenticate("ana@example.com", test_accounts.PW)["name"], "Ana")
        self.assertEqual(remote.alpaca_credentials(ana["id"])[0], "PKCOPYKEY1234567")
        self.assertEqual(remote.trades(ana["id"])[0]["symbol"], "AAPL")
        self.assertEqual(Journal(PG_URL).latest_signals()["signals"][0]["symbol"], "AAPL")
        bo = remote.create_user("bo@example.com", "Bo", test_accounts.PW)     # new ids continue after copied ones
        self.assertGreater(bo["id"], ana["id"])
        with mock.patch.dict(os.environ, env, clear=True), contextlib.redirect_stdout(io.StringIO()), \
                self.assertRaises(SystemExit) as ctx:                            # never copies over existing data
            main(["--env-file", str(self.tmp / "none.env"), "db", "copy-from-sqlite"])
        self.assertIn("already has data", str(ctx.exception))
        out = io.StringIO()
        with mock.patch.dict(os.environ, env, clear=True), contextlib.redirect_stdout(out):
            main(["--env-file", str(self.tmp / "none.env"), "db", "status"])
        self.assertIn("PostgreSQL database", out.getvalue())
        self.assertIn("users", out.getvalue())


