PG_URL = os.environ.get("POSTGRES_TEST_URL")


def reset_schema():
    db = Database(PG_URL)
    with db.connect() as c:
        c.execute(f"DROP SCHEMA IF EXISTS {PG_SCHEMA} CASCADE")


class TranslationTests(unittest.TestCase):
    def test_placeholders_and_percent_signs(self):
        self.assertEqual(to_postgres_sql("SELECT * FROM t WHERE a=? AND b LIKE 'algo-%' AND c='?'"),
                         "SELECT * FROM t WHERE a=%s AND b LIKE 'algo-%%' AND c='?'")

    def test_schema(self):
        stmts = to_postgres_schema("CREATE TABLE x (id INTEGER PRIMARY KEY AUTOINCREMENT, e TEXT UNIQUE COLLATE NOCASE, "
                                   "p REAL);\nCREATE INDEX IF NOT EXISTS i ON x(e);")
        self.assertEqual(stmts[0], "CREATE TABLE x (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                                   "e TEXT UNIQUE, p DOUBLE PRECISION)")
        self.assertEqual(len(stmts), 2)

    def test_describe_never_shows_the_password(self):
        url = "postgresql://postgres.abcd:s3cret-pass@aws-0-us-east-1.pooler.supabase.com:5432/postgres"
        text = describe(url)
        self.assertNotIn("s3cret-pass", text)
        self.assertEqual(text, "Supabase database postgres.abcd@aws-0-us-east-1.pooler.supabase.com:5432/postgres")
        self.assertEqual(describe("/x/users.db"), "SQLite file /x/users.db")

    def test_passwords_with_symbols_can_be_pasted_as_is(self):
        # found with a real Supabase password: / and & in it broke the address
        raw = "postgresql://postgres.abcd:p4&_x.Y/Zq.S@aws-0-us-east-1.pooler.supabase.com:5432/postgres"
        fixed = normalize_url(raw)
        self.assertEqual(fixed, "postgresql://postgres.abcd:p4%26_x.Y%2FZq.S@aws-0-us-east-1.pooler.supabase.com:5432/postgres")
        self.assertEqual(describe(raw), "Supabase database postgres.abcd@aws-0-us-east-1.pooler.supabase.com:5432/postgres")
        self.assertEqual(normalize_url("postgresql://u:p@ss#w rd?@h:5432/d?sslmode=require"),
                         "postgresql://u:p%40ss%23w%20rd%3F@h:5432/d?sslmode=require")
        for same in ("postgresql://u:already%26encoded@h:5432/d", "postgresql://u:plain123@h:5432/d",
                     "postgresql://localhost/d", "/path/users.db"):
            self.assertEqual(normalize_url(same), same)
        from unittest import mock

        from algotrader.config import load_settings
        with mock.patch.dict(os.environ, {"DATABASE_URL": f'  "{raw}" '}, clear=True):   # quotes and spaces too
            self.assertEqual(load_settings(env_file="/nonexistent.env").database_url, fixed)

    def test_unreadable_connection_string_gets_a_clear_message(self):
        with self.assertRaises(DatabaseError) as ctx:
            Database("postgresql://user@host:notaport/db")
        self.assertIn("isn't a valid connection string", str(ctx.exception))
        self.assertIn("can't be read", describe("postgresql://user@host:notaport/db"))

    def test_transaction_pooler_is_refused_with_advice(self):
        with self.assertRaises(DatabaseError) as ctx:
            Database("postgresql://postgres.abcd:pw@aws-0-us-east-1.pooler.supabase.com:6543/postgres")
        self.assertIn("Session pooler", str(ctx.exception))

    def test_settings(self):
        from unittest import mock

        from algotrader.config import Settings, load_settings
        with mock.patch.dict(os.environ, {"DATABASE_URL": "postgresql://u:p@h:5432/d"}, clear=True):
            s = load_settings(env_file="/nonexistent.env")
        self.assertEqual((s.journal_db, s.users_db), ("postgresql://u:p@h:5432/d",) * 2)
        local = Settings()
        self.assertEqual((local.journal_db, local.users_db), (local.db_path, local.users_db_path))


class DoctorDatabaseTests(TempDirTest):
    def run_doctor(self, url):
        from algotrader.config import Settings
        from algotrader.doctor import run_doctor
        out = io.StringIO()
        run_doctor(Settings(data_dir=self.tmp, database_url=url, secret_key="m", frontend_dist=self.tmp),
                   out=out, server_url="http://127.0.0.1:9")
        return out.getvalue()

    def test_unreachable_database_is_reported_with_a_fix(self):
        text = self.run_doctor("postgresql://u:p@nonexistent-host.invalid:5432/db")
        self.assertIn("[FAIL] Database", text)
        self.assertIn("DATABASE_URL", text)
        self.assertNotIn(":p@", text)                          # never prints the password

    def test_local_files(self):
        self.assertIn("[ OK ] Database: local files", self.run_doctor(None))

    @unittest.skipUnless(PG_URL, "set POSTGRES_TEST_URL to run against PostgreSQL")
    def test_connected(self):
        reset_schema()
        text = self.run_doctor(PG_URL)
        self.assertIn("[ OK ] Database: PostgreSQL database postgres@127.0.0.1", text)
        self.assertIn("[ OK ] User accounts: none yet", text)


